"""Shared in-memory Sponsor evidence setup; synthetic truth never leaves the fixture."""
from decimal import Decimal as D
from offworld_kernel.build3 import Build3Kernel, RunIdentity
from offworld_kernel.mvp_state import AgentState, AgentKind, BODY_MATERIAL_FAMILIES
from offworld_kernel.model import AccountKind, NodeKind

SEED='BUILD8_SYNTHETIC_LUNAR_ACCESS_V1'
KEY='BODY:MOON:VOLATILES_PRESENT'
KEYS=tuple('BODY:MOON:'+family+'_PRESENT' for family in BODY_MATERIAL_FAMILIES)

def sponsor_setup(private_signal='NEGATIVE', share_private=False, projects=False):
    k=Build3Kernel(RunIdentity(SEED,'v1','AUTHORED_SYNTHETIC_TRUTH','NONCANON',()))
    k.add_node('EARTH:X',NodeKind.EARTH)
    k.add_account('publisher','PUB','EARTH:X',AccountKind.FUNDS,D(10))
    k.add_account('supplier','SUP','EARTH:X',AccountKind.SUPPLIER,D(0))
    k.add_agent(AgentState('PUB',AgentKind.PUBLIC,'EARTH:X','publisher',{'EXPLORE'}))
    for name in ('A','B','C'):
        k.add_account(name,name,'EARTH:X',AccountKind.FUNDS,D(1))
        if projects:
            k.add_account('cash:'+name,name,'EARTH:X',AccountKind.PROJECT_CASH)
            k.add_project('project:'+name,'EARTH:X','cash:'+name,{name:D(1)})
        k.add_agent(AgentState(name,AgentKind.PRIVATE_SPONSOR,'EARTH:X',name,
                               ({'REQUEST_FINANCE','DEVELOP'} | ({'EXPLORE'} if name=='B' else set())) if projects else {'REQUEST_FINANCE'},('RETURN',),priors={key:D('.5') for key in KEYS}))
    # The truth is authored, not admitted from World Authority. Both observations
    # are generated by the existing keyed noisy-observation transition.
    public,_,public_draw=k.explore_paid(1,'PUB','','','supplier',D(1),channel='REMOTE',
        public=False,false_positive=D('.2'),false_negative=D('.2'),update_belief=False,
        body_id='MOON',question_ref='BODY_MATERIAL_CHARACTERIZATION',
        body_truth={family:True for family in BODY_MATERIAL_FAMILIES})
    obs=next(o for o in public if o.question_ref=='VOLATILES_PRESENT')
    if obs.signal!='POSITIVE':
        raise AssertionError('seed does not produce required positive public control')
    for observation in public:
        belief_key='BODY:MOON:'+observation.question_ref
        k.publish_observation(1,'PUB',observation.id,'EXPERIMENT_PUBLIC',
            tuple((name,belief_key,D('.8') if observation.question_ref=='VOLATILES_PRESENT' else D('.5'),
                   D('.2') if observation.question_ref=='VOLATILES_PRESENT' else D('.5'))
                  for name in ('A','B','C')))
    # Private sensor belongs to B. The flip changes authored truth, not merely
    # an observation. It is a separate synthetic scenario, NOT same-world replay.
    k.agents['B'].capabilities.add('EXPLORE')
    private,_,_=k.explore_paid(2,'B','','','supplier',D(0),channel='REMOTE',
        public=False,false_positive=D('.2'),false_negative=D('.2'),update_belief=False,
        body_id='MOON',question_ref='WATER_BEARING_MATERIAL_PRESENT',
        body_truth=(private_signal=='POSITIVE'))
    if private.signal!=private_signal:
        raise AssertionError('seed does not yield requested private signal')
    # Trial-only mapping: water-bearing signal informs the volatile hypothesis.
    # This is an authored inference assumption, not a World Authority contract.
    if share_private:
        k.publish_observation(2,'B',private.id,'EXPERIMENT_SHARED',
            tuple((name,KEY,D('.8'),D('.2')) for name in ('A','C')))
    # Existing publication transition updates the B recipient belief through
    # the same recipient-side Bayes rule without exposing the hidden truth.
    # B can publish to itself because it owns the observation.
    k.publish_observation(2,'B',private.id,'EXPERIMENT_PRIVATE',(('B',KEY,D('.8'),D('.2')),))
    public_ids=tuple(o.id for o in public)
    return k,public,obs,private,public_draw
